import {readFile,writeFile} from "node:fs/promises";
import {gunzipSync} from "node:zlib";
import {createHash} from "node:crypto";
const file="dist/index.html";
let html=await readFile(file,"utf8");
const input=Buffer.from(html),inputSha=createHash("sha256").update(input).digest("hex");
if(input.length!==192096) throw Error(`V1.32 bytes ${input.length} != 192096`);
if(inputSha!=="803c9d65de24c4403967c63944d505ac34e6f0101be580dd6c7f9c9eb25fd90b") throw Error(`V1.32 SHA mismatch ${inputSha}`);
const packed=await readFile("assets/v133/report-v133.fragment.gz");
const packedSha=createHash("sha256").update(packed).digest("hex");
if(packedSha!=="9a2f947db6877aa7f6dc3411144647b1b1a936833c82d927a842fe5d5a999e85") throw Error(`V1.33 packed SHA mismatch ${packedSha}`);
const report=gunzipSync(packed).toString("utf8");
const reportSha=createHash("sha256").update(Buffer.from(report)).digest("hex");
if(reportSha!=="0f782076b3a28110289064f2a961eb5705d1758ab2a5d295ef495d95d7462261") throw Error(`V1.33 report SHA mismatch ${reportSha}`);
const a=html.indexOf("function ReportHubScreen("),b=html.indexOf("/* ── CUSTOMERS TAB",a);
if(a<0||b<0) throw Error("ReportHubScreen markers missing");
html=html.slice(0,a)+report+html.slice(b);
html=html.replace("taphoa_ui_cache_v32_","taphoa_ui_cache_v33_");
const out=Buffer.from(html),sha=createHash("sha256").update(out).digest("hex");
if(out.length!==216232) throw Error(`V1.33 bytes ${out.length} != 216232`);
if(sha!=="ae5425fb06f12b6a93ea00f1960381e69a649e64d8c8b6315946990ed469f84d") throw Error(`V1.33 SHA mismatch ${sha}`);
await writeFile(file,out);
console.log(`REPORT PASS V1.33 ${out.length} ${sha}`);
